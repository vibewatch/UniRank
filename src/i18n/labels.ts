export function subjectKey(label: string): string {
  return label
    .toLowerCase()
    .replace(/&|,|\band\b|-/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

export function subjectLabel(label: string, locale: Locale): string {
  return locale === 'zh' ? (ZH_SUBJECTS[subjectKey(label)] ?? label) : label;
}
